import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import * as z from 'zod';

import {
  concreteAICatalogSchema,
  schemaRegistry,
} from '../dist/internal/schemas.js';
import { implementedSpecRevision } from '../dist/spec-revision.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const jsonPath = join(root, 'schema', 'ai-catalog.schema.json');
const modulePath = join(root, 'src', 'generated', 'ai-catalog-json-schema.ts');
const check = process.argv.includes('--check');

const converted = z.toJSONSchema(concreteAICatalogSchema, {
  target: 'draft-2020-12',
  io: 'input',
  reused: 'ref',
  metadata: schemaRegistry,
});
const { $schema, ...structuralSchema } = converted;
const schema = {
  $schema: $schema ?? 'https://json-schema.org/draft/2020-12/schema',
  $id: `urn:vercel-labs:ai-catalog-sdk:schema:ai-catalog:${implementedSpecRevision.commit}`,
  title: 'AI Catalog',
  description: 'An SDK-maintained structural schema for an AI Catalog.',
  'x-ai-catalog-specification': implementedSpecRevision,
  ...structuralSchema,
};

const json = `${JSON.stringify(schema, null, 2)}\n`;
const moduleSource = `import type { JsonSchema } from '../json-schema-types.js';

// Generated by scripts/generate-schema.mjs. Do not edit manually.
export const aiCatalogJsonSchema: JsonSchema = ${JSON.stringify(schema, null, 2)};
`;

async function matches(path, expected) {
  try {
    return (await readFile(path, 'utf8')) === expected;
  } catch (error) {
    if (error?.code === 'ENOENT') return false;
    throw error;
  }
}

if (check) {
  const [jsonMatches, moduleMatches] = await Promise.all([
    matches(jsonPath, json),
    matches(modulePath, moduleSource),
  ]);
  if (!jsonMatches || !moduleMatches) {
    console.error('Generated JSON Schema artifacts are out of date.');
    process.exitCode = 1;
  }
} else {
  await Promise.all([
    mkdir(dirname(jsonPath), { recursive: true }),
    mkdir(dirname(modulePath), { recursive: true }),
  ]);
  await Promise.all([
    writeFile(jsonPath, json),
    writeFile(modulePath, moduleSource),
  ]);
}
